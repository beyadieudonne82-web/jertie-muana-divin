foreach ($e in $liste) {
  $num = $e[0]; $dest = $e[1]
  $f = Get-ChildItem -Path $source -File | Where-Object { $_.BaseName -like "*WA$num" -and $_.Extension -match "^\.(jpg|jpeg)$" } | Select-Object -First 1
  if ($f) {
    $cible = Join-Path "images" $dest
    New-Item -ItemType Directory -Force -Path (Split-Path $cible) | Out-Null
    Copy-Item -LiteralPath $f.FullName -Destination $cible -Force
    $ok++
  } else { $manque += $num }
}
